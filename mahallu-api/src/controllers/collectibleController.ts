/** Receipt numbers may be typed by hand only by admins (mahall admin / super admin). */
const canSetReceiptNo = (req: AuthRequest) => req.isSuperAdmin || req.user?.role === 'mahall';

/**
 * Create a receipt with a unique number. Server-generated by default (PREFIX/FY/00042). An admin may
 * supply their own number; it must be unused in this mahallu, otherwise 409.
 */
const createReceiptDoc = async (req: AuthRequest, type: ReceiptType, data: any) => {
  const Model = modelFor(type);
  const tenantId = String(data.tenantId);
  const supplied = typeof data.receiptNo === 'string' ? data.receiptNo.trim() : '';
  delete data.receiptNo;

  if (supplied && canSetReceiptNo(req)) {
    const taken = await Model.exists({ tenantId: new mongoose.Types.ObjectId(tenantId), receiptNo: supplied });
    const dupMsg = `Receipt number ${supplied} is already used in this mahallu. Leave the number empty to get the next one automatically, or enter a different number.`;
    if (taken) throw new HttpError(409, dupMsg);
    try {
      const doc = new Model({ ...data, receiptNo: supplied });
      await doc.save();
      return doc;
    } catch (err: any) {
      if (isDuplicateKeyError(err)) throw new HttpError(409, dupMsg);
      throw err;
    }
  }

  for (let attempt = 0; attempt < 5; attempt++) {
    const receiptNo = await allocateReceiptNo(Model, type, tenantId);
    try {
      const doc = new Model({ ...data, receiptNo });
      await doc.save();
      return doc;
    } catch (err: any) {
      if (isDuplicateKeyError(err) && attempt < 4) continue; // lost a race: take the next number
      throw err;
    }
  }
  throw new HttpError(500, 'Could not allocate a receipt number. Please try again.');
};

