/** GET /collectibles/payment-requests?status=pending|approved|rejected&type=varisangya|zakat */
export const getPaymentRequests = async (req: AuthRequest, res: Response) => {
  try {
    const status = (req.query.status as string) || 'pending';
    if (!['pending', 'approved', 'rejected'].includes(status)) {
      return res.status(400).json({ success: false, message: 'Invalid status' });
    }
    const type = req.query.type as string | undefined;

    const scope: any = tenantScope(req);
    if (!scope.tenantId && req.isSuperAdmin && req.query.tenantId) scope.tenantId = req.query.tenantId;

    // Approved tab lists member-originated requests only (admin-recorded payments live on the normal lists)
    const base: any = { ...scope, source: 'member' };
    base.status = status;

    const wantV = !type || type === 'varisangya';
    const wantZ = !type || type === 'zakat';

    const [vs, zs] = await Promise.all([
      wantV
        ? Varisangya.find(base)
            .populate('familyId', 'houseName')
            .populate('memberId', 'name phone')
            .sort({ createdAt: -1 })
            .limit(500)
            .lean()
        : Promise.resolve([]),
      wantZ
        ? Zakat.find(base).populate('payerId', 'name phone').sort({ createdAt: -1 }).limit(500).lean()
        : Promise.resolve([]),
    ]);

    const rows = [
      ...vs.map((v: any) => ({
        ...v,
        type: 'varisangya',
        payerName: v.memberId?.name || v.familyId?.houseName || '-',
      })),
      ...zs.map((z: any) => ({ ...z, type: 'zakat' })),
    ].sort((a: any, b: any) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());

    const counts = await Promise.all(
      ['pending', 'approved', 'rejected'].map(async (st) => {
        const q = { ...scope, source: 'member', status: st };
        const [vc, zc] = await Promise.all([
          Varisangya.aggregate([{ $match: castTenant(q) }, { $group: { _id: null, n: { $sum: 1 }, amount: { $sum: '$amount' } } }]),
          Zakat.aggregate([{ $match: castTenant(q) }, { $group: { _id: null, n: { $sum: 1 }, amount: { $sum: '$amount' } } }]),
        ]);
        return [st, { count: (vc[0]?.n || 0) + (zc[0]?.n || 0), amount: (vc[0]?.amount || 0) + (zc[0]?.amount || 0) }];
      })
    );

    res.json({ success: true, data: rows, summary: Object.fromEntries(counts) });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

const castTenant = (q: any) => ({
  ...q,
  ...(q.tenantId && mongoose.Types.ObjectId.isValid(String(q.tenantId))
    ? { tenantId: new mongoose.Types.ObjectId(String(q.tenantId)) }
    : {}),
});

const loadPendingRequest = async (req: AuthRequest, res: Response) => {
  const { type, id } = req.params;
  const Model: any = requestModel(type);
  if (!Model) {
    res.status(400).json({ success: false, message: 'Invalid payment type' });
    return null;
  }
  if (!mongoose.Types.ObjectId.isValid(id)) {
    res.status(400).json({ success: false, message: 'Valid payment request ID is required' });
    return null;
  }
  const doc = await Model.findOne({ _id: id, ...tenantScope(req), source: 'member' });
  if (!doc) {
    res.status(404).json({ success: false, message: 'Payment request not found' });
    return null;
  }
  if (doc.status !== 'pending') {
    res.status(409).json({ success: false, message: `Payment request already ${doc.status}` });
    return null;
  }
  return { doc, type, Model };
};

/** POST /collectibles/payment-requests/:type/:id/approve */
export const approvePaymentRequest = async (req: AuthRequest, res: Response) => {
  try {
    const loaded = await loadPendingRequest(req, res);
    if (!loaded) return;
    const { doc, type, Model } = loaded;

    // Approving posts money dated paymentDate: refuse up front when that period is closed
    if (!(await ensurePeriodOpen(res, doc.tenantId, doc.paymentDate))) return;

    // Atomic claim so double-clicks / two admins cannot apply side effects twice.
    // A request keeps its own number if it has one; otherwise take the next FY number (retry on a race).
    let claimed: any = null;
    for (let attempt = 0; attempt < 5; attempt++) {
      const receiptNo = doc.receiptNo || (await allocateReceiptNo(Model, type as ReceiptType, String(doc.tenantId)));
      try {
        claimed = await Model.findOneAndUpdate(
          { _id: doc._id, status: 'pending' },
          {
            $set: {
              status: 'approved',
              receiptNo,
              reviewedBy: req.user?._id,
              reviewedAt: new Date(),
            },
            $unset: { rejectReason: '' },
          },
          { new: true }
        );
        break;
      } catch (err: any) {
        if (isDuplicateKeyError(err) && !doc.receiptNo && attempt < 4) continue;
        throw err;
      }
    }
    if (!claimed) {
      return res.status(409).json({ success: false, message: 'Payment request already reviewed' });
    }

    if (type === 'varisangya') await applyVarisangyaSideEffects(claimed);
    else await applyZakatSideEffects(claimed);

    res.json({ success: true, data: claimed, message: 'Payment request approved' });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

/** POST /collectibles/payment-requests/:type/:id/reject  { reason } */
export const rejectPaymentRequest = async (req: AuthRequest, res: Response) => {
  try {
    const reason = String(req.body?.reason || '').trim();
    if (!reason) {
      return res.status(400).json({ success: false, message: 'A rejection reason is required' });
    }
    const loaded = await loadPendingRequest(req, res);
    if (!loaded) return;
    const { doc, Model } = loaded;

    const updated = await Model.findOneAndUpdate(
      { _id: doc._id, status: 'pending' },
      { $set: { status: 'rejected', rejectReason: reason, reviewedBy: req.user?._id, reviewedAt: new Date() } },
      { new: true }
    );
    if (!updated) {
      return res.status(409).json({ success: false, message: 'Payment request already reviewed' });
    }
    res.json({ success: true, data: updated, message: 'Payment request rejected' });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};
