/**
 * Wallet identity rule: ONE wallet per family. A payment that carries a familyId (even together with
 * a memberId, e.g. a member-portal request) credits the family wallet {tenant, family}. A member
 * wallet {tenant, member} exists only for payers without a family.
 * Old data is not migrated: reversals/edits locate the wallet through the receipt's own credit
 * Transaction first (see walletIdForReceipt), so legacy {family, member} wallets stay consistent.
 */
const walletFilter = (r: any) =>
  r.familyId
    ? { tenantId: r.tenantId, familyId: r.familyId, memberId: { $exists: false } }
    : { tenantId: r.tenantId, familyId: { $exists: false }, memberId: r.memberId };

/** The wallet a receipt was actually credited to (via its credit transaction), else the rule above. */
const walletForReceipt = async (receipt: any) => {
  const credit: any = await Transaction.findOne({
    tenantId: receipt.tenantId,
    referenceId: receipt._id,
    referenceType: 'varisangya',
    type: 'credit',
    reversalOf: { $exists: false },
  })
    .sort({ createdAt: 1 })
    .select('walletId')
    .lean();
  if (credit?.walletId) {
    const w: any = await Wallet.findById(credit.walletId);
    if (w) return w;
  }
  return Wallet.findOne(walletFilter(receipt));
};

/** Validate family / member / collector references of a payment body against the caller's tenant. */
const validateRefs = async (tenantId: any, body: Record<string, any>): Promise<string | null> => {
  if (body.familyId && !(await refBelongsToTenant(Family, body.familyId, tenantId))) return 'Family not found in this mahallu';
  if (body.memberId && !(await refBelongsToTenant(Member, body.memberId, tenantId))) return 'Member not found in this mahallu';
  if (body.payerId && !(await refBelongsToTenant(Member, body.payerId, tenantId))) return 'Payer not found in this mahallu';
  if (body.collectorId && !(await refBelongsToTenant(Collector, body.collectorId, tenantId))) return 'Collector not found in this mahallu';
  return null;
};
const clampedBalanceChange = (delta: number, date?: Date) => [
  {
    $set: {
      balance: { $max: [0, { $add: [{ $ifNull: ['$balance', 0] }, delta] }] },
      ...(date ? { lastTransactionDate: date } : {}),
    },
  },
];

/** Wallet debit + linked reversal Transaction (keeps the original credit for the audit trail). */
const reverseWalletForReceipt = async (receipt: any, type: ReceiptType, label: string) => {
  if (type !== 'varisangya' || !(receipt.familyId || receipt.memberId)) return;
  const wallet: any = await walletForReceipt(receipt);
  if (!wallet) return;
  await Wallet.updateOne({ _id: wallet._id }, clampedBalanceChange(-receipt.amount) as any);
  // Every still-open wallet transaction of this receipt (the credit plus any amendments) is closed by one reversal
  const open: any[] = await Transaction.find({
    tenantId: receipt.tenantId,
    referenceId: receipt._id,
    referenceType: type,
    reversedBy: { $exists: false },
    reversalOf: { $exists: false },
  }).sort({ createdAt: 1 });
  const original = open.find((t) => t.type === 'credit');
  const reversal: any = await Transaction.create({
    tenantId: receipt.tenantId,
    walletId: wallet._id,
    type: 'debit',
    amount: receipt.amount,
    description: `Reversal: ${label} receipt ${receipt.receiptNo || 'N/A'}`,
    referenceId: receipt._id,
    referenceType: type,
    reversalOf: original?._id,
  });
  if (open.length) {
    await Transaction.updateMany({ _id: { $in: open.map((t) => t._id) } }, { $set: { reversedBy: reversal._id } });
  }
};

const reverseReceiptEffects = async (receipt: any, type: ReceiptType, label: string) => {
  await reverseLedgerEntry(type, receipt._id as any);
  await reverseWalletForReceipt(receipt, type, label);
};

