/** Wallet credit + ledger entry + WhatsApp receipt for an approved Varisangya payment. */
const applyVarisangyaSideEffects = async (varisangya: any) => {
    // Update wallet if familyId or memberId exists
    if (varisangya.familyId || varisangya.memberId) {
      // Atomic credit: concurrent receipts for the same family can no longer overwrite each other's balance
      const matchWallet: any = walletFilter(varisangya);
      const wallet: any = await Wallet.findOneAndUpdate(
        matchWallet,
        { $inc: { balance: varisangya.amount }, $set: { lastTransactionDate: varisangya.paymentDate } },
        { new: true, upsert: true, setDefaultsOnInsert: true }
      );

      // Build description with payer name
      let payerInfo = '';
      if (varisangya.familyId) {
        const family = await Family.findById(varisangya.familyId).select('houseName').lean();
        if (family?.houseName) payerInfo = ` - ${family.houseName}`;
      } else if (varisangya.memberId) {
        const member = await Member.findById(varisangya.memberId).select('name').lean();
        if (member?.name) payerInfo = ` - ${member.name}`;
      }

      // Create transaction
      await Transaction.create({
        tenantId: varisangya.tenantId,
        walletId: wallet._id,
        type: 'credit',
        amount: varisangya.amount,
        description: `Varisangya payment${payerInfo} - ${varisangya.receiptNo || 'N/A'}`,
        referenceId: varisangya._id,
        referenceType: 'varisangya',
      });
    }

    // Auto-post to accounting ledger
    try {
      await postLedgerEntry({
        tenantId: varisangya.tenantId,
        ledgerName: 'Varisangya Collections',
        ledgerType: 'income',
        amount: varisangya.amount,
        description: `Varisangya payment - Receipt ${varisangya.receiptNo || 'N/A'}`,
        date: varisangya.paymentDate,
        source: 'varisangya',
        sourceId: varisangya._id as any,
        paymentMethod: varisangya.paymentMethod,
        referenceNo: varisangya.receiptNo,
      });
    } catch (ledgerError) {
      console.error('Failed to auto-post varisangya to ledger:', ledgerError);
    }

    // WhatsApp digital receipt (fire-and-forget)
    void sendVarisangyaReceipt(varisangya);
};

export const createVarisangya = async (req: AuthRequest, res: Response) => {
  try {
    const varisangyaData = {
      ...req.body,
      tenantId: req.tenantId || req.body.tenantId,
      // admin-recorded payments are always approved; clients cannot override
      status: 'approved',
      source: 'admin',
      requestedBy: undefined,
      reviewedBy: undefined,
      reviewedAt: undefined,
      rejectReason: undefined,
      cancelledAt: undefined,
      cancelledBy: undefined,
      cancelReason: undefined,
      printLog: undefined,
      editHistory: undefined,
      createdBy: userRef(req),
      collectorId: req.body.collectorId || undefined,
    };

    if (!varisangyaData.tenantId) {
      return res.status(400).json({ success: false, message: 'Tenant ID is required' });
    }

    const refError = await validateRefs(varisangyaData.tenantId, varisangyaData);
    if (refError) return res.status(400).json({ success: false, message: refError });
    if (!(await ensurePeriodOpen(res, varisangyaData.tenantId, varisangyaData.paymentDate ?? new Date()))) return;

    const varisangya = await createReceiptDoc(req, 'varisangya', varisangyaData);
    await applyVarisangyaSideEffects(varisangya);

    res.status(201).json({ success: true, data: varisangya });
  } catch (error: any) {
    sendError(res, error);
  }
};

const EDITABLE_FIELDS: Record<ReceiptType, string[]> = {
  varisangya: ['amount', 'paymentDate', 'paymentMethod', 'remarks', 'remarksMl'],
  zakat: ['amount', 'paymentDate', 'paymentMethod', 'remarks', 'remarksMl', 'payerName', 'payerId', 'category'],
};
const FINANCIAL_FIELDS = ['amount', 'paymentDate', 'paymentMethod', 'payerName'];

const sameValue = (a: any, b: any) => {
  if (a instanceof Date || b instanceof Date) return new Date(a as any).getTime() === new Date(b as any).getTime();
  if ((a == null || a === '') && (b == null || b === '')) return true;
  return String(a) === String(b);
};

/** Shared edit flow: whitelisted fields, audit trail (last 20), wallet + ledger kept in sync. */
const updateReceipt = async (req: AuthRequest, res: Response, type: ReceiptType) => {
  try {
    const { id } = req.params;
    const label = type === 'varisangya' ? 'Varisangya' : 'Zakat';
    if (!id || !mongoose.Types.ObjectId.isValid(id)) {
      return res.status(400).json({ success: false, message: `Valid ${type} ID is required` });
    }
    const Model = modelFor(type);
    const query: any = { _id: toObjectId(id) };
    if (req.tenantId) query.tenantId = req.tenantId;

    const existing: any = await Model.findOne(query);
    if (!existing || ['pending', 'rejected'].includes(existing.status)) {
      return res.status(404).json({ success: false, message: `${label} payment not found` });
    }
    if (existing.status === 'cancelled') {
      return res.status(409).json({
        success: false,
        message: 'This receipt is cancelled and can no longer be edited. Record a new receipt instead.',
      });
    }

    // Period lock up front: both the original and the new payment date must be in open periods
    if (!(await ensurePeriodOpen(res, existing.tenantId, [existing.paymentDate, req.body?.paymentDate]))) return;
    if (req.body?.payerId) {
      const refError = await validateRefs(existing.tenantId, { payerId: req.body.payerId });
      if (refError) return res.status(400).json({ success: false, message: refError });
    }

    const changes: Record<string, { from: any; to: any }> = {};
    const oldAmount = existing.amount;
    for (const field of EDITABLE_FIELDS[type]) {
      if (req.body[field] === undefined) continue;
      let next: any = req.body[field];
      if (field === 'amount') {
        next = Number(next);
        if (!Number.isFinite(next) || next < 0) throw new HttpError(400, 'Amount must be a positive number');
      } else if (field === 'paymentDate') {
        next = new Date(next);
        if (isNaN(next.getTime())) throw new HttpError(400, 'Payment date must be a valid date');
      }
      const prev = existing[field];
      if (!sameValue(prev, next)) {
        changes[field] = { from: prev, to: next };
        existing[field] = next;
      }
    }

    if (Object.keys(changes).length === 0) {
      const same = await populateAudit(Model.findById(existing._id));
      return res.json({ success: true, data: same });
    }

    const entry = { at: new Date(), by: userRef(req), changes };
    existing.editHistory = [...(existing.editHistory || []), entry].slice(-20);
    await existing.save();

    // Keep wallet and ledger consistent with the edited receipt
    if (type === 'varisangya' && (existing.familyId || existing.memberId) && (changes.amount || changes.paymentDate)) {
      const wallet: any = await walletForReceipt(existing);
      if (wallet) {
        const delta = existing.amount - oldAmount;
        await Wallet.updateOne({ _id: wallet._id }, clampedBalanceChange(delta, existing.paymentDate) as any);
        if (delta !== 0) {
          await Transaction.create({
            tenantId: existing.tenantId,
            walletId: wallet._id,
            type: delta > 0 ? 'credit' : 'debit',
            amount: Math.abs(delta),
            description: `Amended: receipt ${existing.receiptNo || 'N/A'} amount ${oldAmount} to ${existing.amount}`,
            referenceId: existing._id,
            referenceType: type,
          });
        }
      }
    }
    if (FINANCIAL_FIELDS.some((f) => changes[f])) {
      try {
        await reverseLedgerEntry(type, existing._id as any);
        await postLedgerEntry(ledgerPostParams(existing, type));
      } catch (ledgerError) {
        console.error(`Failed to update ${type} ledger entry:`, ledgerError);
      }
    }

    const updated = await populateAudit(
      type === 'varisangya'
        ? Varisangya.findById(existing._id)
            .populate('familyId', 'houseName')
            .populate({ path: 'memberId', select: 'name familyName', populate: { path: 'familyId', select: 'houseName' } })
        : Zakat.findById(existing._id).populate('payerId', 'name')
    );
    res.json({ success: true, data: updated });
  } catch (error: any) {
    sendError(res, error);
  }
};

export const updateVarisangya = (req: AuthRequest, res: Response) => updateReceipt(req, res, 'varisangya');

/** Hard delete (super admin only, enforced on the route). Reverses wallet and ledger first. */
const deleteReceipt = async (req: AuthRequest, res: Response, type: ReceiptType) => {
  try {
    const { id } = req.params;
    const label = type === 'varisangya' ? 'Varisangya' : 'Zakat';
    if (!id || !mongoose.Types.ObjectId.isValid(id)) {
      return res.status(400).json({ success: false, message: `Valid ${type} ID is required` });
    }
    const Model = modelFor(type);
    const query: any = { _id: toObjectId(id) };
    if (req.tenantId) query.tenantId = req.tenantId;

    const existing: any = await Model.findOne(query);
    if (!existing) {
      return res.status(404).json({ success: false, message: `${label} payment not found` });
    }

    // Pending/rejected requests and cancelled receipts were never applied or are already reversed.
    const stillApplied = !['pending', 'rejected', 'cancelled'].includes(existing.status);
    if (stillApplied && !(await ensurePeriodOpen(res, existing.tenantId, existing.paymentDate))) return;
    if (stillApplied) await reverseReceiptEffects(existing, type, `${label} (deleted)`);

    await Model.findByIdAndDelete(existing._id);
    res.json({ success: true, message: `${label} payment deleted successfully` });
  } catch (error: any) {
    sendError(res, error);
  }
};

export const deleteVarisangya = (req: AuthRequest, res: Response) => deleteReceipt(req, res, 'varisangya');

/** POST /collectibles/:type/:id/cancel { reason } - void a receipt, keep its number, reverse the money. */
export const cancelReceipt = async (req: AuthRequest, res: Response) => {
  try {
    const type = req.params.type as ReceiptType;
    if (type !== 'varisangya' && type !== 'zakat') {
      return res.status(400).json({ success: false, message: 'Invalid receipt type' });
    }
    const reason = String(req.body?.reason || '').trim();
    if (reason.length < 5) {
      return res.status(400).json({
        success: false,
        message: 'Please enter a reason of at least 5 characters so the cancellation can be audited later.',
      });
    }
    const { id } = req.params;
    if (!mongoose.Types.ObjectId.isValid(id)) {
      return res.status(400).json({ success: false, message: 'Valid receipt ID is required' });
    }
    const Model = modelFor(type);
    const existing: any = await Model.findOne({ _id: id, ...tenantScope(req) });
    if (!existing) return res.status(404).json({ success: false, message: 'Receipt not found' });
    if (existing.status === 'cancelled') {
      return res.status(409).json({ success: false, message: 'This receipt is already cancelled.' });
    }
    if (existing.status === 'pending' || existing.status === 'rejected') {
      return res.status(409).json({
        success: false,
        message: 'This is a payment request, not an issued receipt. Approve or reject it from Payment Approvals.',
      });
    }

    if (!(await ensurePeriodOpen(res, existing.tenantId, existing.paymentDate))) return;

    // Atomic claim so two clicks cannot reverse the money twice
    const claimed: any = await Model.findOneAndUpdate(
      { _id: existing._id, status: { $nin: ['pending', 'rejected', 'cancelled'] } },
      { $set: { status: 'cancelled', cancelledAt: new Date(), cancelledBy: userRef(req), cancelReason: reason } },
      { new: true }
    );
    if (!claimed) return res.status(409).json({ success: false, message: 'This receipt was just changed by someone else. Refresh and try again.' });

    try {
      await reverseReceiptEffects(claimed, type, `${type === 'varisangya' ? 'Varisangya' : 'Zakat'} (cancelled)`);
    } catch (err) {
      // Put the receipt back so books and receipt stay consistent
      await Model.updateOne(
        { _id: claimed._id },
        { $set: { status: existing.status || 'approved' }, $unset: { cancelledAt: '', cancelledBy: '', cancelReason: '' } }
      );
      console.error('Receipt cancel failed, status restored:', err);
      return res.status(500).json({ success: false, message: 'The receipt could not be cancelled and is unchanged. Please try again.' });
    }

    const data = await populateAudit(Model.findById(claimed._id));
    res.json({ success: true, data, message: 'Receipt cancelled. Its number is kept and the amounts are reversed.' });
  } catch (error: any) {
    sendError(res, error);
  }
};

/** POST /collectibles/:type/:id/print-log - first print is the original, later ones are duplicates (decided here). */
export const recordReceiptPrint = async (req: AuthRequest, res: Response) => {
  try {
    const type = req.params.type as ReceiptType;
    if (type !== 'varisangya' && type !== 'zakat') {
      return res.status(400).json({ success: false, message: 'Invalid receipt type' });
    }
    const { id } = req.params;
    if (!mongoose.Types.ObjectId.isValid(id)) {
      return res.status(400).json({ success: false, message: 'Valid receipt ID is required' });
    }
    const Model = modelFor(type);
    const scope = { _id: id, ...tenantScope(req) };
    const existing: any = await Model.findOne(scope);
    if (!existing) return res.status(404).json({ success: false, message: 'Receipt not found' });
    if (['pending', 'rejected', 'cancelled'].includes(existing.status)) {
      return res.status(409).json({ success: false, message: 'Only active receipts can be printed. This one is ' + existing.status + '.' });
    }

    const at = new Date();
    const by = userRef(req);
    let updated: any = await Model.findOneAndUpdate(
      { ...scope, 'printLog.kind': { $ne: 'original' } },
      { $push: { printLog: { at, by, kind: 'original' } } },
      { new: true }
    );
    let kind: 'original' | 'duplicate' = 'original';
    if (!updated) {
      kind = 'duplicate';
      updated = await Model.findOneAndUpdate(scope, { $push: { printLog: { at, by, kind: 'duplicate' } } }, { new: true });
    }
    res.json({ success: true, data: { kind, isDuplicate: kind === 'duplicate', printLog: updated?.printLog || [] } });
  } catch (error: any) {
    sendError(res, error);
  }
};

